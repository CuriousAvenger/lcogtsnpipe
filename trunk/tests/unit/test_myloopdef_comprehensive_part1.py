def _make_psf_fits(tmp_path, name='test.psf.fits'):
    """Create a minimal PSF FITS with required headers."""
    data = np.zeros((25, 25), dtype=np.float32)
    hdr = fits.Header()
    hdr['PAR1'] = 2.0
    hdr['PAR2'] = 2.0
    hdr['PSFRAD'] = 10.0
    hdr['PSFHEIGH'] = 1000.0
    hdr['NPSFSTAR'] = 2
    hdr['ID1'] = 1
    hdr['X1'] = 100.0
    hdr['Y1'] = 100.0
    hdr['ID2'] = 2
    hdr['X2'] = 200.0
    hdr['Y2'] = 200.0
    # Note: NAXIS1/NAXIS2 are auto-generated by astropy from the data shape;
    # do NOT set them manually or they will conflict with the mandatory header.
    path = tmp_path / name
    hdu = fits.PrimaryHDU(data=data, header=hdr)
    hdu.writeto(str(path), overwrite=True)
    return str(path)


